import { writeFile } from 'node:fs/promises';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { courses as cybersecurityCourses } from '../src/data/courses.js';
import { courses as dataScienceCourses } from '../src/data/dataScienceCourses.js';

export const catalogueSources = [
  { department: 'cybersecurity', courses: cybersecurityCourses },
  { department: 'dataScience', courses: dataScienceCourses },
];

export const quoteSql = (value) => `'${String(value).replaceAll("'", "''")}'`;
const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

export function catalogueRows(sources = catalogueSources) {
  const byKey = new Map();
  for (const { department, courses } of sources) {
    for (const { level, code, title } of courses) {
      const databaseLevel = `${level}L`;
      const key = JSON.stringify([department, databaseLevel, code]);
      // CYB 311–313 recur as SIWES courses at the same level. The offering
      // form resolves each code to its first catalogue entry too.
      if (!byKey.has(key)) byKey.set(key, {
        department, level: databaseLevel, course_code: code, course_title: title,
      });
    }
  }
  return [...byKey.values()].sort((a, b) =>
    compare(a.department, b.department) ||
    compare(a.level, b.level) ||
    compare(a.course_code, b.course_code));
}

export function generateCatalogueSeed(sources = catalogueSources) {
  const rows = catalogueRows(sources);
  if (rows.length === 0) throw new Error('Cannot generate an empty catalogue seed.');
  const values = rows.map(({ department, level, course_code, course_title }) =>
    `  (${[department, level, course_code, course_title].map(quoteSql).join(', ')})`).join(',\n');
  const keys = rows.map(({ department, level, course_code }) =>
    `  (${[department, level, course_code].map(quoteSql).join(', ')})`).join(',\n');
  const departments = [...new Set(sources.map(({ department }) => department))].sort()
    .map(quoteSql).join(', ');

  return `-- GENERATED by scripts/gen-catalogue-seed.mjs. Do not hand-edit.
-- After changing a catalogue, run npm run gen:catalogue-seed, then run this file
-- in the Supabase SQL editor after 20261102040000_offering_course_codes.sql.
BEGIN;
INSERT INTO public.catalogue_courses (department, level, course_code, course_title)
VALUES
${values}
ON CONFLICT (department, level, course_code)
DO UPDATE SET course_title = EXCLUDED.course_title;

DELETE FROM public.catalogue_courses
WHERE department IN (${departments})
  AND (department, level, course_code) NOT IN (VALUES
${keys}
  );
COMMIT;
NOTIFY pgrst, 'reload schema';
`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeFile(fileURLToPath(new URL('../supabase/seed/catalogue_courses.sql', import.meta.url)),
    generateCatalogueSeed(), 'utf8');
}
